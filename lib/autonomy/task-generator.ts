/**
 * Create a task generator from a recommendation
 */
export function createTaskFromRecommendation(
  recommendation: Recommendation,
  generator?: AutonomousTaskGenerator
): AutonomousTask {
  const gen = generator || new AutonomousTaskGenerator();
  
  // Determine the appropriate input type based on recommendation type
  if (recommendation.type === 'investigate_decline' || recommendation.type === 'address_anomaly') {
    const trend = recommendation.sourceTrends[0];
    if (trend) {
      return gen.generateFromKPIAnomaly({
        metric: recommendation.sourceMetrics[0] || 'unknown',
        trend,
        severity: recommendation.priority === 'critical' ? 'critical' : 'warning',
        deviationPercent: trend.changePercent,
        expectedRange: { min: trend.avg7dValue * 0.9, max: trend.avg7dValue * 1.1 },
      });
    }
  }
  
  if (recommendation.type === 'review_blocked_tasks') {
    return gen.generateFromBlockedWork({
      taskId: `blocked_${Date.now()}`,
      taskTitle: recommendation.title,
      blockedReason: recommendation.description,
      blockedSince: new Date(Date.now() - 24 * 60 * 60 * 1000).toISOString(),
      blockerType: 'dependency',
      impactScore: recommendation.confidenceScore,
    });
  }
  
  // Default: treat as strategic gap
  return gen.generateFromStrategicGap({
    objectiveId: `obj_${Date.now()}`,
    objectiveTitle: recommendation.title,
    gapType: 'coverage',
    description: recommendation.description,
    timeline: recommendation.priority === 'critical' ? 'immediate' : 'short_term',
    estimatedImpact: recommendation.suggestedAction.estimatedImpact,
  });
}

/**
 * Batch process a list of recommendations into tasks
 */
export function batchGenerateTasks(
  recommendations: Recommendation[],
  generator?: AutonomousTaskGenerator
): AutonomousTask[] {
  const gen = generator || new AutonomousTaskGenerator();
  
  return recommendations
    .filter(r => r.confidenceScore >= 50) // Only generate tasks for confident recommendations
    .map(r => createTaskFromRecommendation(r, gen));
}

